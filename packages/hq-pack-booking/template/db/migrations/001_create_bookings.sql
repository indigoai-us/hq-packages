CREATE TABLE IF NOT EXISTS bookings (
  id text NOT NULL,
  event_type_id text,
  kind text,
  host_ids text,
  start_at bigint,
  end_at bigint,
  duration bigint,
  status text,
  location text,
  timezone text,
  manage_token_hash text,
  created_by text,
  agent_key_id text,
  member_id text,
  agent_note text,
  utm text,
  link_id text,
  claim_keys text,
  calendar text,
  calendar_status text,
  cancel_reason text,
  canceled_at bigint,
  canceled_by text,
  reschedule_count bigint,
  no_show boolean,
  created_at bigint,
  updated_at bigint,
  PRIMARY KEY (id)
);
